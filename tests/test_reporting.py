class ReportingTest(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary_directory = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary_directory.name).resolve()
        self.session = Session.create(self.root / "session")

    def tearDown(self) -> None:
        self.temporary_directory.cleanup()

    def test_report_is_sorted_and_separates_every_accounting_measurement(self) -> None:
        targets = {
            name: Target(
                id=f"user-caches:{name}",
                path=str(self.root / "home" / "Library" / "Caches" / name),
                kind="directory",
                risk=Risk.SAFE_REGENERABLE,
                fingerprint=name * 64,
                logical_bytes=size,
            )
            for name, size in (("z-verified", 30), ("a-suspended", 20), ("m-skipped", 10))
        }
        self.session.write_manifest(
            Manifest(
                batches=(
                    Batch("z-batch", (targets["z-verified"],)),
                    Batch("a-batch", (targets["m-skipped"], targets["a-suspended"])),
                ),
                issues=(
                    Issue("scan.warning", Severity.WARNING, "partial measurement"),
                ),
                inventory_digest="a" * 64,
            )
        )
        self.session.transition(targets["z-verified"].id, "approved")
        self.session.transition(targets["z-verified"].id, "applied")
        self.session.transition(targets["z-verified"].id, "verified")
        self.session.transition(targets["a-suspended"].id, "approved")
        self.session.transition(targets["a-suspended"].id, "suspended")
        self.session.transition(targets["m-skipped"].id, "skipped")
        self.session.add_issue(
            Issue(
                "executor.fingerprint-changed",
                Severity.BATCH_ERROR,
                "changed",
                targets["a-suspended"].id,
            )
        )
        record_batch_outcome(
            self.session,
            "apply",
            BatchOutcome(
                batch_id="z-batch",
                logical_bytes_removed=30,
                logical_bytes_removed_by_target=((targets["z-verified"].id, 30),),
                free_space_before=1_000,
                free_space_after=1_024,
                regenerated_bytes=7,
                regenerated_target_ids=(targets["z-verified"].id,),
            ),
        )

        report = render_report(self.session)

        self.assertLess(report.index("## Batch `a-batch`"), report.index("## Batch `z-batch`"))
        self.assertLess(report.index("user-caches:a-suspended"), report.index("user-caches:m-skipped"))
        for identifier in (
            "user-caches:a-suspended",
            "user-caches:m-skipped",
            "user-caches:z-verified",
        ):
            self.assertIn(identifier, report)
        self.assertIn("Estimated logical bytes: 30", report)
        self.assertIn("Removed logical bytes: 30", report)
        self.assertIn("Observed `df` free-space delta: 24", report)
        self.assertIn("Regenerated bytes: 7", report)
        self.assertIn("Regenerated target ids: `user-caches:z-verified`", report)
        self.assertIn("### warning", report)
        self.assertIn("### batch_error", report)
        self.assertIn("Required user actions", report)
        self.assertIn("Create a new session and rescan `user-caches:a-suspended`", report)
        self.assertIn("Logical target sizes are not net recovered space", report)
        self.assertNotIn("net recovered space: 30", report.casefold())

    def test_unobserved_and_absent_measurements_are_unknown_not_zero(self) -> None:
        target = Target(
            id="user-caches:absent",
            path=str(self.root / "home" / "Library" / "Caches" / "absent"),
            kind="directory",
            risk=Risk.SAFE_REGENERABLE,
            fingerprint="a" * 64,
            logical_bytes=42,
        )
        self.session.write_manifest(
            Manifest(
                batches=(Batch("safe-user-caches", (target,)),),
                inventory_digest="b" * 64,
            )
        )
        self.session.transition(target.id, "approved")
        self.session.transition(target.id, "applied")
        self.session.transition(target.id, "verified")
        record_batch_outcome(
            self.session,
            "apply",
            BatchOutcome(
                batch_id="safe-user-caches",
                issues=(
                    Issue(
                        "executor.target-absent",
                        Severity.INFORMATIONAL,
                        "already absent",
                        target.id,
                    ),
                ),
            ),
        )

        report = render_report(self.session)

        self.assertIn("Removed logical bytes: unknown", report)
        self.assertIn("Observed `df` free-space delta: unknown", report)
        self.assertIn("Regenerated bytes: 0", report)
        self.assertNotIn("Removed logical bytes: 0", report)

    def test_partial_removal_accounting_is_durable_unknown_and_strictly_validated(self) -> None:
        known = Target(
            id="user-caches:known",
            path=str(self.root / "home" / "Library" / "Caches" / "known"),
            kind="directory",
            risk=Risk.SAFE_REGENERABLE,
            fingerprint="a" * 64,
            logical_bytes=7,
        )
        target = Target(
            id="user-caches:partial",
            path=str(self.root / "home" / "Library" / "Caches" / "partial"),
            kind="directory",
            risk=Risk.SAFE_REGENERABLE,
            fingerprint="b" * 64,
            logical_bytes=42,
        )
        self.session.write_manifest(
            Manifest(
                batches=(Batch("safe-user-caches", (known, target)),),
                inventory_digest="c" * 64,
            )
        )
        self.session.transition(known.id, "approved")
        self.session.transition(known.id, "applied")
        self.session.transition(known.id, "verified")
        self.session.transition(target.id, "approved")
        self.session.transition(target.id, "suspended")
        issue = Issue(
            "executor.removal-accounting-uncertain",
            Severity.BATCH_ERROR,
            "Exact removal was interrupted; removed logical bytes are unknown.",
            target.id,
        )
        record_batch_outcome(
            self.session,
            "apply",
            BatchOutcome(
                batch_id="safe-user-caches",
                issues=(issue,),
                logical_bytes_removed=None,
                logical_bytes_removed_by_target=((known.id, 7),),
                uncertain_target_ids=(target.id,),
                suspended=True,
            ),
        )

        path = self.session.path / "outcomes.json"
        valid = read_json(path)
        operation = valid["operations"][0]
        self.assertIsNone(operation["logical_bytes_removed"])
        self.assertEqual(operation["uncertain_target_ids"], [target.id])
        report = render_report(self.session)
        self.assertIn("Removed logical bytes: unknown", report)
        self.assertIn(f"Removal accounting uncertainty: `{target.id}`", report)
        self.assertIn(
            f"| `{target.id}` | suspended | 42 | unknown |", report
        )
        self.assertIn(f"| `{known.id}` | verified | 7 | 7 |", report)
        self.assertIn("Exact removal was interrupted", report)

        mutations = {
            "numeric total with uncertainty": lambda item: item.update(
                logical_bytes_removed=0
            ),
            "missing uncertain target": lambda item: item.update(
                uncertain_target_ids=[]
            ),
            "duplicate uncertain target": lambda item: item.update(
                uncertain_target_ids=[target.id, target.id]
            ),
            "unknown uncertain target": lambda item: item.update(
                uncertain_target_ids=["user-caches:forged"]
            ),
        }
        for label, mutate in mutations.items():
            with self.subTest(label=label):
                document = copy.deepcopy(valid)
                mutate(document["operations"][0])
                atomic_write_json(path, document)
                with self.assertRaises(ValueError):
                    render_report(self.session)
        atomic_write_json(path, valid)

    def test_report_surfaces_engine_validated_admin_checksum_and_manual_boundary(self) -> None:
        home = self.root / "home"
        cache_root = home / "Library" / "Caches"
        target_path = cache_root / "admin-cache"
        target_path.mkdir(parents=True)
        (target_path / "entry.bin").write_bytes(b"cache")
        identity = inspect_path(target_path, (cache_root,))
        target = Target(
            id="user-caches:admin-cache",
            path=identity.canonical,
            kind=identity.kind,
            risk=Risk.SAFE_REGENERABLE,
            fingerprint=identity.fingerprint,
            logical_bytes=identity.logical_bytes,
        )
        batch = Batch("safe-user-caches", (target,))
        self.session.write_manifest(
            Manifest(batches=(batch,), inventory_digest="c" * 64)
        )
        self.session.transition(target.id, "approved")
        script_path = self.session.path / "admin.zsh"
        checksum = generate_admin_script(
            batch,
            script_path,
            self.session.path / "admin-result.json",
            trusted_home=home,
        )

        report = render_report(self.session, trusted_home=home)

        self.assertIn("engine validation: passed", report)
        self.assertIn(str(script_path), report)
        self.assertIn(checksum, report)
        self.assertIn("execute exactly that validated script path, not a copy", report)
        self.assertIn("does not close the later manual validation-to-execution gap", report)

    def test_report_rejects_forged_or_internally_inconsistent_outcomes(self) -> None:
        target = Target(
            id="user-caches:accounted",
            path=str(self.root / "home" / "Library" / "Caches" / "accounted"),
            kind="directory",
            risk=Risk.SAFE_REGENERABLE,
            fingerprint="a" * 64,
            logical_bytes=5,
        )
        self.session.write_manifest(
            Manifest(
                batches=(Batch("safe-user-caches", (target,)),),
                inventory_digest="b" * 64,
            )
        )
        record_batch_outcome(
            self.session,
            "apply",
            BatchOutcome(
                batch_id="safe-user-caches",
                logical_bytes_removed=5,
                logical_bytes_removed_by_target=((target.id, 5),),
                free_space_before=100,
                free_space_after=105,
                regenerated_bytes=1,
                issues=(
                    Issue("z.warning", Severity.WARNING, "later"),
                    Issue("a.info", Severity.INFORMATIONAL, "earlier"),
                ),
            ),
        )
        path = self.session.path / "outcomes.json"
        valid = read_json(path)
        mutations = {
            "forged delta": lambda item: item.update(free_space_delta=999),
            "partial endpoints": lambda item: item.update(
                free_space_before=None, free_space_delta=None
            ),
            "negative endpoint": lambda item: item.update(free_space_after=-1),
            "negative regenerated": lambda item: item.update(regenerated_bytes=-1),
            "boolean sequence": lambda item: item.update(sequence=True),
            "empty regenerated id": lambda item: item["regenerated_target_ids"].append(""),
            "reversed issues": lambda item: item["issues"].reverse(),
            "duplicate issue": lambda item: item["issues"].append(
                copy.deepcopy(item["issues"][0])
            ),
            "unknown field": lambda item: item.update(forged=True),
            "noncanonical issue": lambda item: item["issues"].append(
                {
                    "code": "bad",
                    "severity": "warning",
                    "message": "bad",
                    "unknown": True,
                }
            ),
        }
        for label, mutate in mutations.items():
            with self.subTest(label=label):
                document = copy.deepcopy(valid)
                mutate(document["operations"][0])
                atomic_write_json(path, document)
                with self.assertRaises(ValueError):
                    render_report(self.session)
        atomic_write_json(path, valid)

    def test_report_validates_bound_admin_artifacts_after_batch_is_verified(self) -> None:
        home = self.root / "home"
        cache_root = home / "Library" / "Caches"
        target_path = cache_root / "admin-cache"
        target_path.mkdir(parents=True)
        (target_path / "entry.bin").write_bytes(b"cache")
        identity = inspect_path(target_path, (cache_root,))
        target = Target(
            id="user-caches:admin-cache",
            path=identity.canonical,
            kind=identity.kind,
            risk=Risk.SAFE_REGENERABLE,
            fingerprint=identity.fingerprint,
            logical_bytes=identity.logical_bytes,
        )
        batch = Batch("safe-user-caches", (target,))
        self.session.write_manifest(
            Manifest(batches=(batch,), inventory_digest="c" * 64)
        )
        self.session.transition(target.id, "approved")
        script_path = self.session.path / "admin.zsh"
        generate_admin_script(
            batch,
            script_path,
            self.session.path / "admin-result.json",
            trusted_home=home,
        )
        self.session.transition(target.id, "applied")
        self.session.transition(target.id, "verified")
        terminal_report = render_report(self.session, trusted_home=home)
        self.assertIn("engine validation: passed", terminal_report)
        self.assertIn("not currently authorized for manual execution", terminal_report)
        self.assertNotIn("then execute exactly", terminal_report)
        script_path.write_text("#!/bin/zsh\nexit 0\n", encoding="utf-8")
        state_before = self.session.state

        with self.assertRaises(AdministrativeArtifactError):
            render_report(self.session, trusted_home=home)

        self.assertEqual(Session.load(self.session.path).state, state_before)

    def test_dry_run_outcomes_are_rejected_before_persistence(self) -> None:
        target = Target(
            id="user-caches:dry-run",
            path=str(self.root / "home" / "Library" / "Caches" / "dry-run"),
            kind="directory",
            risk=Risk.SAFE_REGENERABLE,
            fingerprint="a" * 64,
            logical_bytes=5,
        )
        self.session.write_manifest(
            Manifest(
                batches=(Batch("safe-user-caches", (target,)),),
                inventory_digest="b" * 64,
            )
        )
        for removed in (0, 5):
            with self.subTest(removed=removed), self.assertRaises(ValueError):
                record_batch_outcome(
                    self.session,
                    "apply",
                    BatchOutcome(
                        batch_id="safe-user-caches",
                        logical_bytes_removed=removed,
                        logical_bytes_removed_by_target=(
                            ((target.id, removed),) if removed else ()
                        ),
                        dry_run=True,
                    ),
                )
            self.assertFalse((self.session.path / "outcomes.json").exists())

    def test_unresolved_intent_report_ignores_missing_or_malformed_outcomes(self) -> None:
        target = Target(
            id="user-caches:uncertain",
            path=str(self.root / "home" / "Library" / "Caches" / "uncertain"),
            kind="directory",
            risk=Risk.SAFE_REGENERABLE,
            fingerprint="a" * 64,
            logical_bytes=5,
        )
        self.session.write_manifest(
            Manifest(
                batches=(Batch("safe-user-caches", (target,)),),
                inventory_digest="b" * 64,
            )
        )
        self.session.transition(target.id, "approved")
        self.session.begin_mutation_intent(
            operation="apply",
            batch_id="safe-user-caches",
            target_id=target.id,
        )

        for label, malformed in (("missing", False), ("malformed", True)):
            with self.subTest(label=label):
                path = self.session.path / "outcomes.json"
                if malformed:
                    atomic_write_json(path, {"invalid": True})
                elif path.exists():
                    path.unlink()
                report = render_report(self.session)
                self.assertIn("Removed logical bytes: unknown", report)
                self.assertIn(
                    f"Removal accounting uncertainty: `{target.id}`", report
                )
                self.assertIn("`executor.unresolved-mutation-intent`", report)
                self.assertIn("Start a fresh session", report)


